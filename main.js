        // 通路の縁の内側に並べる（マップpx: 半幅-3。床帯の実寸内に収める）
        segs.push({ x1: na.mx, y1: na.my, x2: nb.mx, y2: nb.my, len, off: Math.max(2.5, w / 2 - 3) });
